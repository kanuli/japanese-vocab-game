// Stage 2 exact-form runtime safeguards after the full world-evidence JLPT rebuild.
// Do not perform any broad frequency-based reclassification here: the generated
// audited bundle already contains the calibrated N5-N1 result. This layer is only an
// idempotent exact written-form+reading safeguard for manually cross-checked rows.
(()=>{"use strict";
const O=new Map([
  ["ほてん|補填",{level:"N2",reason:"Mazii/MOJi/時雨 secondary exact-form validation"}],
  ["アップル|アップル",{level:"N5",reason:"時雨 secondary exact-form validation"}]
]);
const rows=Array.isArray(window.ADVANCED_WORDS)?window.ADVANCED_WORDS:[];
let eligible=0,applied=0;
for(const w of rows){
  const reading=String(w?.reading||"").trim();
  const display=String(w?.kanji||w?.displayWord||reading).trim();
  const patch=O.get(`${reading}|${display}`);
  if(!patch)continue;
  eligible++;
  w.level=patch.level;
  w.levelSource="manual-secondary-crosscheck-exact";
  w.stage2LevelCrosscheck=true;
  w.stage2LevelReason=patch.reason;
  applied++;
}
window.VOCAB_STAGE2_LEVEL_OVERRIDE_META={
  version:"20260826-v3-exact-only",
  configured:O.size,
  eligible,
  applied,
  broadReclassificationApplied:0,
  policy:"Exact form+reading safeguards only. All broad JLPT classification is generated by the audited world-evidence recalibration pipeline; runtime frequency-only N1/N2 mass reassignment is prohibited."
};
})();